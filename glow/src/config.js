export function readSliderValue(cfg, id) {
  if (id.startsWith("bw.")) return cfg.biome_weights[id.slice(3)] ?? 0;
  return cfg[id];
}

export function applySliderPatch(cfg, patch) {
  for (const [k, raw] of Object.entries(patch)) {
    const v = Number(raw);
    if (k.startsWith("bw.")) {
      cfg.biome_weights[k.slice(3)] = v;
    } else if (k in cfg) {
      cfg[k] = v;
    }
  }
  return cfg;
}

export function performanceWarning(cfg) {
  if (cfg.tree_density > 2.4 && (cfg.spore_density > 2 || cfg.firefly_population > 2)) {
    return "VERY HIGH VEGETATION + VERY HIGH PARTICLES MAY REDUCE PERFORMANCE.";
  }
  return "";
}

